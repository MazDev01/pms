import { describe, it, expect } from "vitest";
import {
  CSV_HEADERS, จับคู่คอลัมน์, แถวตัวอย่าง, แผ่นค่าที่เลือกได้, เนื้อไฟล์Csv, type ค่าที่ระบบมี,
} from "../../packages/shared/lib/customerImportTemplate";
import { สร้างไฟล์Xlsx } from "../../packages/shared/lib/exportWorkbook";
import { แยกสมุดงานจากXlsx, แยกตารางจากข้อความ } from "../../packages/shared/lib/importSheet";

// บอสแจ้ง 9 ก.ย. 69: "กดโหลดฟอร์มมากรอก ต้องมีข้อมูลครบและซิงก์กับระบบ อัปกลับแล้วต้องไม่ติดขัด"
//   เทสต์นี้จำลองเส้นทางจริงทั้งเส้น — สร้างไฟล์เทมเพลต → อ่านกลับ → จับคู่คอลัมน์ → ต้องได้ครบ 9 ช่อง
//   (E2E บนเบราว์เซอร์อยู่ที่ tests/scenario/import-template-roundtrip.spec.ts แต่ต้องมี Docker ถึงจะรันได้)

// ค่า "ที่ระบบมี" จำลองของสาขาหนึ่ง — ในของจริงมาจากแคตตาล็อก HQ · จังหวัดในภาคของสาขา · ผู้รับผิดชอบของสาขา
const ค่า: ค่าที่ระบบมี = {
  แม่แบบ: ["อาคารเหล็กสำเร็จรูป", "หลังคาคลุมลานจอด"],
  จังหวัด: ["เชียงใหม่", "ลำพูน", "ลำปาง"],
  ผู้รับผิดชอบ: ["สมชาย เชียงใหม่"],
};


describe("เทมเพลตนำเข้าลูกค้าเดิม", () => {
  it("ไฟล์ Excel ที่โหลดไป กรอกแล้วนำเข้ากลับได้ครบทุกช่อง", async () => {
    const blob = สร้างไฟล์Xlsx([
      { ชื่อ: "ลูกค้าเดิม", หัวตาราง: CSV_HEADERS, แถว: [แถวตัวอย่าง(ค่า)] },
      แผ่นค่าที่เลือกได้(ค่า),
    ]);
    const เล่ม = await แยกสมุดงานจากXlsx(await blob.arrayBuffer());
    expect([...เล่ม.keys()]).toEqual(["ลูกค้าเดิม", "ค่าที่เลือกได้"]);

    const ได้ = จับคู่คอลัมน์(เล่ม.get("ลูกค้าเดิม")!);
    expect(ได้).toHaveLength(1);
    expect(ได้[0]).toEqual({
      company: "บจ. ตัวอย่างสตีล",
      name: "คุณสมชาย ใจดี",
      phone: "081-234-5678",
      email: "contact@example.com",
      address: "26 หมู่ 3 ต.หนองบัว อ.เมือง จ.เชียงใหม่ 50000",
      province: "เชียงใหม่",
      category: "อาคารเหล็กสำเร็จรูป",
      joinDate: "2025-10-05",
      owner: "สมชาย เชียงใหม่",
    });
    // ไม่มีช่องไหนถูกปล่อยว่าง — ถ้ามี ผู้ใช้จะต้องมาไล่พิมพ์เองทีละรายหลังนำเข้า
    expect(Object.values(ได้[0]).filter(v => !v)).toEqual([]);
  });

  it("แผ่น “ค่าที่เลือกได้” ลอกค่าจริงจากระบบมาครบ ไม่ตัดทิ้งเมื่อสามคอลัมน์ยาวไม่เท่ากัน", () => {
    const แผ่น = แผ่นค่าที่เลือกได้(ค่า);
    expect(แผ่น.แถว).toHaveLength(3);                       // ยาวตามคอลัมน์ที่มีค่ามากสุด (จังหวัด 3 รายการ)
    expect(แผ่น.แถว.map(r => r[0]).filter(Boolean)).toEqual(ค่า.แม่แบบ);
    expect(แผ่น.แถว.map(r => r[1])).toEqual(ค่า.จังหวัด);
    expect(แผ่น.แถว.map(r => r[2]).filter(Boolean)).toEqual(ค่า.ผู้รับผิดชอบ);
  });

  it("ค่าตัวอย่างในแถวแรกใช้ของจริงจากระบบ ไม่ใช่ค่าที่ฝังตายตัว", () => {
    const แถว = แถวตัวอย่าง(ค่า);
    expect(แถว[5]).toBe(ค่า.จังหวัด[0]);
    expect(แถว[6]).toBe(ค่า.แม่แบบ[0]);
    expect(แถว[8]).toBe(ค่า.ผู้รับผิดชอบ[0]);
    // สาขาที่ยังไม่มีข้อมูลพวกนี้ ต้องได้ไฟล์เปล่า ๆ ไม่ใช่ค่ามั่ว
    const ว่าง = แถวตัวอย่าง({ แม่แบบ: [], จังหวัด: [], ผู้รับผิดชอบ: [] });
    expect([ว่าง[5], ว่าง[6], ว่าง[8]]).toEqual(["", "", ""]);
  });

  it("ไฟล์ CSV นำเข้ากลับได้ และบรรทัดหมายเหตุท้ายไฟล์ถูกข้ามให้เอง", () => {
    const ข้อความ = เนื้อไฟล์Csv(ค่า);
    const ได้ = จับคู่คอลัมน์(แยกตารางจากข้อความ(ข้อความ));
    expect(ได้).toHaveLength(1);                              // 4 บรรทัด "#" + บรรทัดว่าง ต้องไม่กลายเป็นลูกค้า
    expect(ได้[0].category).toBe(ค่า.แม่แบบ[0]);
    expect(ได้[0].province).toBe(ค่า.จังหวัด[0]);
    // หมายเหตุต้องลอกค่าจริงมาให้ครบ จะได้ก๊อปไปวางได้เลย
    for (const v of [...ค่า.แม่แบบ, ...ค่า.จังหวัด, ...ค่า.ผู้รับผิดชอบ]) expect(ข้อความ).toContain(v);
  });
});
