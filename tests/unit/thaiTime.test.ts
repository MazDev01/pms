import { describe, it, expect } from "vitest";
import { ชั่วโมงนาทีไทย, วันเวลาไทย, parseThaiDate } from "../../packages/shared/lib/thaiDate";

// บอสแจ้ง 14 ก.ย. 69: หน้าบันทึกการใช้งานโชว์ "14 ก.ย. 2569 · 02:03" ทั้งที่เข้าระบบตอน 09:03 เวลาไทย
//   ต้นเหตุ = เซิร์ฟเวอร์ Vercel ตั้งเครื่องเป็น UTC แล้วโค้ดอ่านชั่วโมงด้วย getHours()
//   เทสต์ทุกข้อใช้ "จังหวะเวลาจริง" แบบมี Z ต่อท้าย → ผลต้องเหมือนกันไม่ว่าเครื่องที่รันตั้งโซนไหน
//   ตรวจซ้ำแบบเครื่องเซิร์ฟเวอร์ได้ด้วย: TZ=UTC npx vitest run tests/unit/thaiTime.test.ts

describe("เวลาไทย", () => {
  it("เคสที่บอสเจอ: 02:03 UTC ต้องขึ้นเป็น 09:03", () => {
    expect(วันเวลาไทย(new Date("2026-09-14T02:03:00Z"))).toBe("14 ก.ย. 2569 · 09:03");
    expect(ชั่วโมงนาทีไทย(new Date("2026-09-14T02:03:00Z"))).toBe("09:03");
  });

  it("ข้ามเที่ยงคืน: ดึกของ UTC เป็นเช้าวันถัดไปของไทย — วันที่ต้องเลื่อนตามด้วย", () => {
    // 20:30 UTC วันที่ 13 = 03:30 วันที่ 14 ที่ไทย · ถ้าคิดผิดจะนับเข้า "กิจกรรมวันนี้" ผิดวัน
    expect(วันเวลาไทย(new Date("2026-09-13T20:30:00Z"))).toBe("14 ก.ย. 2569 · 03:30");
  });

  it("ข้ามปี: 31 ธ.ค. ดึก ๆ ของ UTC เป็นวันขึ้นปีใหม่ของไทย", () => {
    expect(วันเวลาไทย(new Date("2026-12-31T17:00:00Z"))).toBe("1 ม.ค. 2570 · 00:00");
  });

  it("เติมศูนย์หน้าเลขหลักเดียว", () => {
    expect(ชั่วโมงนาทีไทย(new Date("2026-09-14T00:05:00Z"))).toBe("07:05");
  });

  it("รูปแบบที่ออกไป ต้องให้ตัวอ่านวันที่ไทยอ่านกลับได้ (หน้า /hq/audit ใช้รูปแบบเดียวกัน)", () => {
    const d = parseThaiDate(วันเวลาไทย(new Date("2026-09-13T20:30:00Z")));
    expect([d?.getFullYear(), d?.getMonth(), d?.getDate()]).toEqual([2026, 8, 14]);
  });
});
