// กติกามูลค่าลูกค้าเป้าหมาย — ต้องบังคับเหมือนกันทุกฟอร์ม (ฟอร์มเพิ่ม · แผงแก้ไข · เพิ่มงานขายใหม่)
import { describe, it, expect } from "vitest";
import { ตรวจมูลค่าลูกค้าเป้าหมาย, MAX_LEAD_VALUE } from "../../packages/shared/lib/leadValue";

describe("ตรวจมูลค่าลูกค้าเป้าหมาย", () => {
  it("เว้นว่างได้ — ยังไม่รู้มูลค่าไม่ถือว่าผิด", () => {
    expect(ตรวจมูลค่าลูกค้าเป้าหมาย("")).toBe("");
    expect(ตรวจมูลค่าลูกค้าเป้าหมาย("   ")).toBe("");
  });

  it("รับได้ทุกแบบที่เซลส์พิมพ์จริง", () => {
    for (const v of ["1400000", "1.4M", "฿1,400,000", "480K", "2.8B"]) {
      expect(ตรวจมูลค่าลูกค้าเป้าหมาย(v), `ควรรับ "${v}"`).toBe("");
    }
  });

  it("อ่านไม่ออก ต้องฟ้อง ห้ามผ่านเป็น ฿0 เงียบ ๆ", () => {
    for (const v of ["abcxyz", "-5000000", "0", "฿"]) {
      expect(ตรวจมูลค่าลูกค้าเป้าหมาย(v), `ควรฟ้อง "${v}"`).toContain("อ่านไม่ออก");
    }
  });

  it("เกินเพดานต้องฟ้อง และเพดานพอดีต้องผ่าน", () => {
    expect(ตรวจมูลค่าลูกค้าเป้าหมาย(String(MAX_LEAD_VALUE))).toBe("");
    expect(ตรวจมูลค่าลูกค้าเป้าหมาย(String(MAX_LEAD_VALUE + 1))).toContain("สูงเกินจริง");
    expect(ตรวจมูลค่าลูกค้าเป้าหมาย("2500B")).toContain("สูงเกินจริง");
  });
});
