import { describe, it, expect } from "vitest";
import { scaleSubtypePrice, scaleSubtypePrices } from "../../packages/shared/lib/repricing";

// ── ปรับราคากลางแล้วแม่แบบย่อยต้องขยับตาม (บอสแจ้ง 19 ส.ค. 69) ──────────────────
// เดิมปุ่ม "ปรับราคา" แตะเฉพาะราคาแม่แบบหลัก แม่แบบย่อยที่ตั้งราคาเฉพาะไว้ค้างราคาเก่าตลอด
// ใบเสนอราคาที่ออกจากแม่แบบย่อยจึงคิดราคาเดิม ทั้งที่ผู้ดูแลเชื่อว่าปรับทั้งกลุ่มไปแล้ว
describe("ปรับราคาแม่แบบย่อยตามแม่แบบหลัก", () => {
  it("รักษาสัดส่วนที่แพงกว่า/ถูกกว่าราคาหลักไว้เท่าเดิม", () => {
    // ย่อยแพงกว่าหลัก 40% (7000 จาก 5000) · หลักขึ้นเป็น 6000 (+20%) → ย่อยต้องเป็น 8400 (ยังแพงกว่า 40%)
    expect(scaleSubtypePrice(7000, 5000, 6000)).toBe(8400);
  });

  it("ราคาหลักลดลง ราคาย่อยต้องลดตาม", () => {
    expect(scaleSubtypePrice(8400, 6000, 5000)).toBe(7000);
  });

  it("ปัดเป็นจำนวนเต็ม และไม่มีทางต่ำกว่า 1 บาท (ฐานข้อมูลบังคับว่าต้องเป็นบวก)", () => {
    expect(scaleSubtypePrice(3333, 5000, 5100)).toBe(3400);
    expect(scaleSubtypePrice(2, 5000, 1)).toBe(1);
  });

  it("ราคาหลักเดิมเป็น 0/ติดลบ → คืนค่าเดิม ไม่เดามั่ว", () => {
    expect(scaleSubtypePrice(7000, 0, 6000)).toBe(7000);
    expect(scaleSubtypePrice(7000, 5000, 0)).toBe(7000);
  });

  it("ปรับทั้งชุดพร้อมกัน", () => {
    const out = scaleSubtypePrices({ "สระว่ายน้ำในร่ม": "9800", "สนามแบดมินตัน": 7000 }, 7000, 7700);
    expect(out).toEqual({ "สระว่ายน้ำในร่ม": 10780, "สนามแบดมินตัน": 7700 });
  });

  it("ไม่ติ๊ก 'ปรับตามสัดส่วน' → ราคาย่อยคงเดิมทุกตัว", () => {
    const out = scaleSubtypePrices({ a: "9800" }, 7000, 9000, false);
    expect(out).toEqual({ a: 9800 });
  });

  it("ช่องที่เว้นว่าง/อ่านไม่ออก ต้องหลุดออกจากชุด (= กลับไปใช้ราคาแม่แบบหลัก) ไม่ใช่บันทึกเป็น 0", () => {
    const out = scaleSubtypePrices({ a: "", b: "abc", c: "0", d: "5000" }, 5000, 6000);
    expect(out).toEqual({ d: 6000 });
  });
});
