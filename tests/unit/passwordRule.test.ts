// กติการหัสผ่านชุดเดียวทั้งระบบ — ทุกทางที่ตั้งรหัสผ่านได้ใช้ตัวนี้ตรวจที่เซิร์ฟเวอร์
import { describe, it, expect } from "vitest";
import { ตรวจรหัสผ่านใหม่ } from "../../packages/shared/lib/passwordRule";

describe("ตรวจรหัสผ่านใหม่", () => {
  it("ยาวอย่างน้อย 8 ตัว", () => {
    expect(ตรวจรหัสผ่านใหม่("1234567")).toMatch(/อย่างน้อย 8/);
    expect(ตรวจรหัสผ่านใหม่("12345678")).toBeNull();
  });
  it("ห้ามมีช่องว่างทุกชนิด (หน้าเข้าสู่ระบบตัดทิ้ง → เจ้าของเข้าไม่ได้)", () => {
    expect(ตรวจรหัสผ่านใหม่("abcd efgh")).toMatch(/ช่องว่าง/);
    expect(ตรวจรหัสผ่านใหม่(" abcdefgh")).toMatch(/ช่องว่าง/);
    expect(ตรวจรหัสผ่านใหม่("abcdefgh\t")).toMatch(/ช่องว่าง/);
  });
  it("ไม่เกิน 72 ไบต์ (ภาษาไทยตัวละ 3 ไบต์)", () => {
    expect(ตรวจรหัสผ่านใหม่("a".repeat(72))).toBeNull();
    expect(ตรวจรหัสผ่านใหม่("a".repeat(73))).toMatch(/ยาวเกิน/);
    expect(ตรวจรหัสผ่านใหม่("ก".repeat(25))).toMatch(/ยาวเกิน/);
  });
  it("รหัสที่ระบบสุ่มให้ (PEB- + 14 ตัว) ผ่านกติกา", () => {
    expect(ตรวจรหัสผ่านใหม่("PEB-Ab3kLmN8pQrStU")).toBeNull();
  });
});
