// ── ช่องตัวเลือกต้องเริ่มที่ "ยังไม่ระบุ" เสมอ (บอสสั่ง 18 ส.ค. 69 · ย้ำ 25 ส.ค. 69) ──
//
// ถ้า <select> ไม่มีตัวเลือกแรกที่เป็นค่าว่าง เบราว์เซอร์จะโชว์ตัวเลือกแรกในรายการแทน
// หน้าจอจึงบอกว่า "เลือกแล้ว" ทั้งที่ผู้ใช้ไม่เคยเลือก → ได้ข้อมูลที่ไม่มีใครระบุเข้าฐานเงียบ ๆ
// (บั๊กจริง: แม่แบบในฟอร์มลูกค้าเป้าหมาย 10 ส.ค. · ฟอร์มเพิ่มงานขายใหม่ 25 ส.ค.)
//
// ยกเว้นได้ 2 กรณี — เขียนคำกำกับไว้ในคอมเมนต์เหนือ <select> (ไม่เกิน 6 บรรทัด)
//   "ต้องมีค่าเสมอ"        = ช่องที่ปล่อยว่างไม่ได้จริง ๆ เช่น สถานะ (ของทุกชิ้นต้องมีสถานะ)
//   "ตัวเลือกแรกคือทั้งหมด" = ตัวกรองบนแถบเครื่องมือ ที่ตัวเลือกแรกสร้างจากรายการ (อ่านจากโค้ดตรง ๆ ไม่ได้)
import { readFileSync } from "node:fs";
import { globSync } from "node:fs";

const files = globSync("{apps,packages}/**/*.tsx", { exclude: p => p.includes("node_modules") || p.includes(".next") });
const ผ่านได้ = /value=""|value={""}|value="all"|value="ALL"|value={"?all"?}|value={ALL}|value="ทั้งหมด"/;
let พบ = 0;

for (const f of files) {
  const src = readFileSync(f, "utf8");
  const lines = src.split(/\r?\n/);
  lines.forEach((line, i) => {
    if (!/<select[\s>]/.test(line)) return;
    // ดูตัวเลือกแรก — นับตั้งแต่บรรทัดเดียวกับ <select> ด้วย (บางที่เขียนติดกันบรรทัดเดียว)
    // ช่องที่ "ต้องมีค่าเสมอ" (เช่น สถานะ ที่ปล่อยว่างไม่ได้) เขียนคำนี้กำกับไว้บรรทัดบนได้
    if (/ต้องมีค่าเสมอ|ตัวเลือกแรกคือทั้งหมด/.test(lines.slice(Math.max(0, i - 6), i).join(String.fromCharCode(10)))) return;
    const ถัดไป = lines.slice(i, i + 7).join("\n");
    const ตัวแรก = ถัดไป.indexOf("<option");
    if (ตัวแรก === -1) return;                       // ไม่ได้เขียน option ตรง ๆ (คอมโพเนนต์อื่นดูแล) — ข้าม
    const บรรทัดแรก = ถัดไป.slice(ตัวแรก, ตัวแรก + 200);
    if (ผ่านได้.test(บรรทัดแรก)) return;
    พบ++;
    console.log(`  ${f}:${i + 1} — <select> ตัวเลือกแรกไม่ใช่ "ยังไม่ระบุ/ทั้งหมด"`);
  });
}
console.log(`ช่องตัวเลือกที่ไม่ได้เริ่มที่ "ยังไม่ระบุ": ${พบ}`);
if (พบ > 0) process.exit(1);
