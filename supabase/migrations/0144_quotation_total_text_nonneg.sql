-- ── ข้อความยอดในใบเสนอราคาห้ามติดลบ ────────────────────────────────────────────
--
-- พบจากการทดสอบหาบั๊ก (19 ส.ค. 69): ยิงคำสั่งบันทึกใบเสนอราคาที่ total = '-500000'
--   เข้าฐานข้อมูลตรง ๆ แล้ว "ผ่าน" — ไม่มีอะไรปฏิเสธเลย
--
-- ขอบเขตของปัญหา (ตรวจแล้ว ไม่ได้เดา):
--   · ตัวเลขที่ระบบใช้คำนวณจริงคือ total_value (numeric) ซึ่งมี CHECK >= 0 มาตั้งแต่ 0069 — ปลอดภัยอยู่แล้ว
--   · แต่ total (text) คือข้อความที่ "แสดงบนหน้าจอและบนเอกสารที่ส่งให้ลูกค้า"
--     ติดลบได้ = ตัวแทนเห็นใบเสนอราคายอด -฿500,000 ในรายการ โดยระบบไม่ฟ้องอะไร
--     และยอดที่ลูกค้าเห็นกับยอดที่ระบบรายงานจะคนละเรื่องกัน
--
-- หน้าจอกันไว้แล้ว (ฟอร์มไม่มีช่องให้พิมพ์ยอดเอง — คิดจาก BOQ ให้เสมอ)
-- ใบนี้คือเซฟตี้เน็ตชั้นฐานข้อมูล กันเส้นทางอื่นในอนาคต (API ใหม่ · งานนำเข้าข้อมูล · แก้ผ่าน console)
-- แนวเดียวกับ 0069 ที่ทำกับ total_value ไว้แล้ว
--
-- ยืนยันก่อนใส่: ไม่มีแถวไหนในฐานข้อมูลผิดเงื่อนไขนี้ (ทั้งฐานทดสอบและฐานจริง)
alter table public.quotations
  add constraint quotations_total_text_nonneg
  check (total is null or total !~ '-[0-9]');

comment on constraint quotations_total_text_nonneg on public.quotations is
  'ข้อความยอดในใบเสนอราคาห้ามมีเครื่องหมายลบนำหน้าตัวเลข — ยอดติดลบไม่มีความหมายในเอกสารที่ส่งให้ลูกค้า';
