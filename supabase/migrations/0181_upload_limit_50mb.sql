-- ── เพดานไฟล์แนบ/แบบแปลน 25 MB → 50 MB (บอสเลือก 16 ก.ย. 69) ─────────────────────
--
-- ที่มา: บอสถาม "25 MB มันเล็กไปไหม" — ชุดแบบแปลน PDF / ไฟล์ CAD / ไฟล์นำเสนอของงานอาคารเหล็กเกินได้บ่อย
-- ต้องตรงกับ UPLOAD_MAX_BYTES (packages/shared/lib/uploadLimits.ts) ที่หน้าเว็บตรวจก่อนอัปโหลด
--
-- ⚠️ พร้อมกันนี้เว็บจริงเปลี่ยนเป็นอัปโหลดตรงเข้าที่เก็บไฟล์ (ลิงก์อัปโหลดที่เซิร์ฟเวอร์ออกให้)
--    เดิมส่งไฟล์ผ่าน /api/v1/storage → ติดเพดานคำขอของ Vercel ~4.5 MB (ยิงจริง 6 MB ได้ 413)
--    เพดานจริงจึงเหลือแค่ที่ถังตั้งไว้ในไฟล์นี้
update storage.buckets set file_size_limit = 52428800 -- 50 MB
 where id in ('dealer-files', 'catalog-plans');
