-- ── กัน "บัญชีลูกผสม": เป็นผู้บริหารสำนักงานใหญ่พร้อมกับผูกสาขา ────────────────────
--
-- ช่องโหว่ที่ปิด (ผลตรวจสอบระบบ 7 ส.ค. 69 · ระดับสูง H-2 · ยิงพิสูจน์แล้ว):
--   ผู้ดูแลสูงสุดยิงคำสั่งแก้ตาราง profiles ตรง ๆ ตั้งบทบาทของบัญชีตัวแทน (dealer_code = 'RYG')
--   ให้เป็น SUPER_ADMIN ได้ → ได้บัญชีที่เป็นทั้งผู้ดูแลสูงสุดและตัวแทนพร้อมกัน
--   บัญชีแบบนี้ is_hq() คืนค่าจริง จึงเห็นข้อมูลทุกสาขาทั้งเครือ แต่ยังล็อกอินเข้าแอปตัวแทนได้ปกติ
--   = ทะลุเส้นแบ่ง "สำนักงานใหญ่ / ตัวแทน" ที่เป็นหลักการหลักของระบบทั้งหมด
--
--   หลักฐาน: ยิงคำสั่งจริงแล้วสำเร็จ 1 แถว · ตรวจซ้ำพบว่าบัญชีระยองมองเห็นข้อมูลลูกค้าของ
--   เชียงใหม่ได้เต็มรูปแบบ (ชื่อบริษัท ชื่อผู้ติดต่อ ยอดเงิน) ก่อนจะคืนค่ากลับ
--
-- ทำไมด่านเดิมไม่กัน:
--   • guard_profile_privilege (0026) ปล่อยผ่านทันทีเมื่อ "ผู้แก้" เป็น SUPER_ADMIN
--     โดยไม่ดู "ผลลัพธ์" ว่ากลายเป็นบัญชีที่ไม่ควรมีอยู่หรือเปล่า
--   • เส้นทาง API มีด่านอยู่จริง (users/route.ts เช็ก "นี่เป็นบัญชีตัวแทน — จัดการที่หน้าตัวแทน")
--     แต่ด่านนั้นอยู่แค่ในโค้ดแอป — ยิงเข้าฐานข้อมูลตรง ๆ ข้ามไปได้ทั้งหมด
--
-- แก้ที่ชั้นฐานข้อมูล = ปิดทุกช่องทางพร้อมกัน ไม่ว่าจะมาจากหน้าจอ สคริปต์ หรือเครื่องมือผู้ดูแล
--   บทบาทฝั่งสำนักงานใหญ่  → ห้ามผูกสาขา (dealer_code ต้องว่าง)
--   บทบาทฝั่งตัวแทน        → ต้องผูกสาขาเสมอ (dealer_code ต้องไม่ว่าง)
--
-- ตรวจข้อมูลจริงก่อนแล้ว: 8 บัญชีที่มีอยู่ผ่านกฎนี้ครบทุกแถว ไม่มี dealer_code ที่เป็นค่าว่าง null
alter table public.profiles
  drop constraint if exists profiles_role_scope_ck;

alter table public.profiles
  add constraint profiles_role_scope_ck check (
    case
      when role in ('SUPER_ADMIN', 'HQ_MANAGEMENT', 'HQ_STAFF')
        then coalesce(dealer_code, '') = ''
      else coalesce(dealer_code, '') <> ''
    end
  );

comment on constraint profiles_role_scope_ck on public.profiles is
  'บทบาทสำนักงานใหญ่ต้องไม่ผูกสาขา · บทบาทตัวแทนต้องผูกสาขา — กันบัญชีลูกผสมที่ทะลุเส้นแบ่ง HQ/ตัวแทน (H-2)';
