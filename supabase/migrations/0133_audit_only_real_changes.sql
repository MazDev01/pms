-- ── บันทึกการใช้งาน: จดเฉพาะที่ "เปลี่ยนจริง" ────────────────────────────────────
--
-- บั๊กจริง (เอเจนต์สวมบทผู้ดูแล HQ เจอเอง 10 ส.ค. 69):
--   แก้แม่แบบเพียง 1 ตัว แล้วบันทึกการใช้งานเพิ่มขึ้นทีเดียว 7 แถว —
--   แถวจริง 1 แถว บวก "UPDATE แคตตาล็อก" ของแม่แบบอีก 6 ตัวที่ไม่ได้แตะเลย
--   (โกดังสำเร็จรูป · โรงงาน · อาคารสำเร็จรูป · งานตามแบบ · รีโนเวท · สนามกีฬาในร่ม)
--
-- ต้นเหตุ: ฝั่งแอปบันทึกแคตตาล็อกด้วยการ "เขียนทับทั้งตาราง" ทุกครั้ง (upsert ทั้งชุด)
--   ตัวดักที่ฐานข้อมูลจึงเห็นเป็นการอัปเดตครบทุกแถว แล้วจดทุกแถวตามหน้าที่
--
-- ทำไมต้องแก้: บันทึกการใช้งานมีไว้ตอบว่า "ใครแก้อะไรเมื่อไหร่" เพื่อใช้ตรวจสอบย้อนหลัง
--   การจดว่าผู้ดูแลแก้ของที่เขาไม่ได้แตะ = **กล่าวหาคนผิด** และทำให้ของจริงจมหายในกองข้อมูล
--   (ตอนตรวจพบ ตารางบวมถึง 10,227 แถว ทั้งที่การกระทำจริงมีไม่กี่ครั้ง)
--   บันทึกที่เชื่อไม่ได้ ไม่มีประโยชน์กว่าไม่มีบันทึกเลย เพราะมันสร้างความมั่นใจผิด ๆ
--
-- วิธีแก้ที่เลือก: ใส่เงื่อนไขที่ "ตัวดัก" ให้ทำงานเฉพาะเมื่อเนื้อหาแถวเปลี่ยนจริง
--   แก้ที่นี่จุดเดียวคุ้มทุกทางที่เขียนข้อมูลเข้ามา ไม่ต้องไล่แก้ทุกที่ที่เรียกใช้
--   และไม่ต้องพึ่งว่าฝั่งแอปจะ "ขยันส่งเฉพาะแถวที่แก้" ซึ่งพลาดได้เสมอ

drop trigger if exists trg_catalog_audit on master_catalog;

-- เพิ่ม/ลบ = จดเสมอ · แก้ไข = จดเฉพาะตอนเนื้อหาต่างจากเดิมจริง
create trigger trg_catalog_audit
  after insert or delete on master_catalog
  for each row execute function public.log_catalog_change();

create trigger trg_catalog_audit_update
  after update on master_catalog
  for each row
  when (old.* is distinct from new.*)
  execute function public.log_catalog_change();
