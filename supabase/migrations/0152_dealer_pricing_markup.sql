-- ── ตัวแทนบวกราคาเพิ่มจากราคากลางของสำนักงานใหญ่เองได้ (บอสสั่ง 20 ส.ค. 69) ──────
--
-- กติกาที่มีอยู่แล้วในระบบ: ราคาในแคตตาล็อกแม่แบบ = "ราคากลาง/ต้นทุน" ที่สำนักงานใหญ่ตั้ง
--   ส่วนราคาขายจริงเป็นสิทธิ์ของตัวแทน ตั้งเองได้อิสระ ไม่มีเพดาน ไม่มีขั้นต่ำ
--   แต่ที่ผ่านมาตัวแทนต้องพิมพ์ราคาใหม่ทุกครั้งที่ออกใบ ทั้งที่ส่วนบวกเพิ่มของแต่ละสาขามักคงที่
--
-- ตอนนี้เก็บ "บวกกี่ %" ต่อแม่แบบไว้ที่สาขา แล้วใบเสนอราคาตั้งต้นด้วยราคาขายของสาขานั้นเลย
--   ตัวเลขที่เก็บเป็นเปอร์เซ็นต์ (10 = บวก 10%) · ไม่ตั้ง/0 = ใช้ราคากลางตรง ๆ เหมือนเดิม
--
-- เก็บเป็น jsonb ในตารางตั้งค่าของสาขาตามแบบเดิมของตาราง (ดูหัวไฟล์ 0024):
--   อ่านทั้งก้อนเสมอ · เพิ่มฟิลด์ทีหลังไม่ต้องแก้โครงสร้างอีก
--   รูปร่าง: { "defaultPct": 10, "byTemplate": { "<รหัสแม่แบบ>": 15 } }
--   byTemplate ชนะ defaultPct เสมอ (ตั้งเฉพาะตัวได้ ไม่งั้นใช้ค่ากลางของสาขา)
alter table dealer_settings
  add column if not exists pricing jsonb not null default '{}'::jsonb;

comment on column dealer_settings.pricing is
  'ส่วนบวกเพิ่มจากราคากลางของแต่ละสาขา (เปอร์เซ็นต์) — { defaultPct, byTemplate: { templateId: pct } }';
