-- ── ราคากลางแยกรายแม่แบบย่อย ────────────────────────────────────────────────────
--
-- เดิมราคากลางตั้งได้ระดับ "แม่แบบหลัก" เท่านั้น แม่แบบย่อยทั้งหมดใต้แม่แบบนั้นใช้ราคาเดียวกันหมด
--   เช่น "สนามกีฬาในร่ม" ราคาเดียวคุมทั้ง สนามแบดมินตัน · สนามบาสเกตบอล · สระว่ายน้ำในร่ม
--   ซึ่งต้นทุนจริงต่างกันมาก → BOQ ตั้งต้นของใบเสนอราคาเพี้ยนตั้งแต่แถวแรก
--   ตัวแทนต้องมานั่งแก้ราคา/หน่วยเองทุกใบ ซึ่งย้อนแย้งกับเจตนาของ "ราคากลางที่ HQ คุม"
--
-- เก็บเป็น jsonb แทนตารางใหม่ เพราะ:
--   • แม่แบบย่อยเองก็เก็บเป็น array อยู่ในแถวเดียวกันอยู่แล้ว (คอลัมน์ subtypes) — อยู่ด้วยกันจึงแก้พร้อมกันได้ในคำสั่งเดียว
--   • จำนวนน้อยมาก (ทั้งระบบ 28 รายการ) ไม่ต้องการ index หรือการ join
--   • ตารางใหม่จะต้องมี RLS/สิทธิ์/ตัวดักบันทึกอีกชุด โดยไม่ได้อะไรเพิ่ม
--
-- รูปแบบ: { "ชื่อแม่แบบย่อย": ราคา, ... }  ตัวอย่าง {"สระว่ายน้ำในร่ม": 9800}
-- ไม่มีคีย์ = แม่แบบย่อยนั้นใช้ราคาของแม่แบบหลัก (พฤติกรรมเดิม — ข้อมูลเก่าจึงไม่กระทบเลย)

alter table public.master_catalog
  add column if not exists subtype_prices jsonb not null default '{}'::jsonb;

comment on column public.master_catalog.subtype_prices is
  'ราคากลางรายแม่แบบย่อย {ชื่อ: ราคา} — ไม่มีคีย์ = ใช้ราคาของแม่แบบหลัก (คอลัมน์ price)';

-- ราคาต้องเป็นตัวเลขบวกเสมอ — เหตุผลเดียวกับ 0084 ที่บังคับกับคอลัมน์ price
-- ราคา 0 หรือติดลบเคยทำให้ BOQ ตั้งต้นว่างเปล่าโดยไม่มีอะไรฟ้อง แล้วตัวแทนออกใบไม่ได้เลย
--
-- ใช้ jsonb_path_exists (immutable · ไม่ต้องมี subquery) — CHECK ของ Postgres ห้ามมี subquery
-- เงื่อนไข: ห้ามมีค่าที่ "ไม่ใช่ตัวเลข" และห้ามมีตัวเลขที่ "น้อยกว่าหรือเท่ากับ 0"
alter table public.master_catalog
  drop constraint if exists master_catalog_subtype_prices_positive;
alter table public.master_catalog
  add constraint master_catalog_subtype_prices_positive check (
        not jsonb_path_exists(subtype_prices, '$.* ? (@.type() != "number")')
    and not jsonb_path_exists(subtype_prices, '$.* ? (@.type() == "number" && @ <= 0)')
  );
