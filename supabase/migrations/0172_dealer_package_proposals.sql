-- ช่องข้อมูลมีเท่าที่มีที่มาจริง: แพ็กเกจ Standard/Exclusive + เงื่อนไข จากไฟล์ของเบนจามิน
--   มูลค่าแพ็กเกจเป็นช่องให้ HQ กรอกเอง ไม่บังคับ (ไฟล์ยังไม่มีตัวเลขจริง ห้ามเติมให้)
