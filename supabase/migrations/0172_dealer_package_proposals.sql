--   · เลขที่ใบ DP-ปี-NNNN ฐานข้อมูลออกให้เสมอ — ผู้เรียกกำหนดเองไม่ได้ และแก้ภายหลังไม่ได้
--   · สถานะเดินหน้าได้ทางเดียว: ร่าง → ส่งแล้ว → ตอบรับ / ปฏิเสธ (ข้ามจากร่างไปตอบรับไม่ได้)
--   · ส่งแล้วแก้เนื้อหาไม่ได้ (เปลี่ยนได้แค่สถานะ/หมายเหตุ) และลบไม่ได้ — เป็นหลักฐานว่าเสนออะไรไป
