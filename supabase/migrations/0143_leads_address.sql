-- ── ที่อยู่ของลูกค้าเป้าหมาย ─────────────────────────────────────────────────────
--
-- บอสแจ้ง (19 ส.ค. 69): "ตอนเพิ่มลูกค้าเป้าหมายไม่มีที่อยู่ แต่พอเป็นลูกค้าแล้วมี"
--   ระเบียนลูกค้ามีคอลัมน์ address มาตั้งแต่แรก (0001) แต่ลูกค้าเป้าหมายไม่มี
--   พอปิดการขายแล้วแปลงเป็นลูกค้า จึงไม่มีที่อยู่จะส่งต่อ — เซลส์ต้องไปตามถามลูกค้าใหม่
--   ทั้งที่ตอนคุยครั้งแรกก็ได้ที่อยู่มาแล้ว (ใช้ออกใบเสนอราคา/ไปดูหน้างาน)
--
-- เก็บเป็น text ช่องเดียวเหมือนฝั่งลูกค้า (ที่อยู่เต็มบรรทัดเดียว) — ให้ส่งต่อกันได้ตรง ๆ
-- ไม่มีที่อยู่ = NULL (หน้าจอขึ้น "—") ห้ามใส่ค่าว่างหลอกว่ามีข้อมูล
alter table public.leads
  add column if not exists address text;

comment on column public.leads.address is
  'ที่อยู่ลูกค้า — กรอกตอนเพิ่ม/แก้ลูกค้าเป้าหมาย · ส่งต่อเป็นที่อยู่ของลูกค้าเมื่อปิดการขายสำเร็จ';
