-- ปัญหา: trigger on_quote_won (0003 · แก้คีย์ใน 0012) สร้าง "ลูกค้าผี id=0"
--
--   insert into customers(id, ...) values (coalesce(new.customer_id, new.deal_id), ...)
--
--   แอปใช้ customer_id = 0 เป็นค่าแทน "ใบนี้ออกให้ลีด ยังไม่มีลูกค้า" (ไม่ใช่ NULL)
--   แต่ coalesce ข้ามเฉพาะ NULL → coalesce(0, x) คืน 0 เสมอ
--
--   พิสูจน์กับ DB จริงแล้ว (ตารางว่าง รีโปรสด):
--     • ตั้งใบที่ customer_id=0 เป็น won → เกิดแถว customers id=0 · name=NULL
--       ทุกใบถัดไปที่ปิดแบบเดียวกันไหลเข้าแถวเดิม (on conflict) → ยอดลูกค้าหลายรายกองรวมกัน
--     • สลับ won → lost → won → total_value เพิ่มจาก 1M เป็น 2M (นับซ้ำ · เงื่อนไข
--       old.status is distinct from 'won' เป็นจริงทุกรอบ)
--
-- ทำไม "ลบ" ไม่ใช่ "แก้ trigger":
--   ถ้าแก้เป็น nullif(coalesce(customer_id, deal_id), 0) แล้วข้ามค่า null
--   ปรากฏว่า trigger จะ "ไม่เคยสร้างลูกค้าในเส้นทางปกติเลย" — ใบที่ผูกลีด (customer_id=0)
--   ถูกข้ามหมด ส่วนใบที่ผูกลูกค้าจริง (customer_id>0) ลูกค้าก็มีอยู่แล้ว (on conflict do nothing)
--   = โค้ดตายที่ยังเสี่ยงสร้างความประหลาดใจ · ลบทิ้งสะอาดกว่า
--
-- แหล่งเดียวหลังจากนี้ = convertLeadToCustomer ในแอป (SalesContext) ซึ่ง:
--   • ออก id จริงจากตัวนับ atomic ของ DB (next_entity_id) ไม่ใช่ 0
--   • พาข้อมูลจากลีดมาครบ (ผู้ติดต่อ/เบอร์/อีเมล/จังหวัด/หมวด/โลโก้/เจ้าของ/มูลค่า)
--   • มี matchCustomers กันลูกค้าซ้ำ (trigger ทำไม่ได้ทั้งสามอย่าง)
--   ทั้งสองปุ่มปิดการขาย (ลิ้นชักลีด + "ลูกค้าตอบรับ" บนใบเสนอราคา) เดินผ่านทางนี้แล้ว
--   (ฝั่งแอปแก้ setQuotationStatus ให้เรียก convertLeadToCustomer มาคู่กับ migration นี้)
--
-- ปลอดภัย: ตารางงานขายว่างทั้งหมด (0 แถว) — ไม่มีลูกค้าผีค้างให้ต้องล้าง

drop trigger if exists trg_quote_won on quotations;
drop function if exists public.on_quote_won();

