"use client";

// ─── ฉากหลังของป๊อปอัพ: ปิดเมื่อคลิกนอกกล่อง แต่ต้องไม่ปิดเพราะจังหวะคลิกที่ไม่ได้ตั้งใจ ──────
//
// ปัญหาที่เจอจริง (11 ส.ค. 69): ผู้ใช้กดปุ่มเปิดป๊อปอัพแบบดับเบิลคลิก (หรือกดรัวสองที)
//   คลิกแรกเปิดป๊อปอัพ → ฉากหลังมาคลุมทั้งจอทันทีตรงตำแหน่งเดียวกับปุ่ม
//   คลิกที่สองจึงไปตกบนฉากหลัง = สั่งปิดทันที
//   ผลบนหน้าจอ: ป๊อปอัพเด้งขึ้นแล้วหายวับ ดูเหมือนจอกะพริบ/มีอะไรซ้อนกันแวบหนึ่ง
//   (ยืนยันด้วยการยิงจริงบนเวอร์ชัน build จริง: ดับเบิลคลิก → นับป๊อปอัพได้ 0 อัน)
//
// อีกจังหวะที่ไม่ควรปิด: กดเมาส์ค้างในกล่อง (เช่นลากเลือกข้อความ) แล้วปล่อยนอกกล่อง
//   เดิมนับเป็น "คลิกนอกกล่อง" → ปิดทิ้งทั้งที่ผู้ใช้กำลังทำงานอยู่ในฟอร์ม
//
// วิธีกัน: ปิดได้ก็ต่อเมื่อ "กดเมาส์ลงบนฉากหลังเอง" และ "ป๊อปอัพเปิดมาเกินช่วงกันสะบัดแล้ว"
import { useCallback, useEffect, useRef } from "react";

/** ช่วงกันคลิกที่สองของดับเบิลคลิก — สั้นพอที่คนกดตั้งใจปิดจริงจะไม่รู้สึกว่าต้องรอ */
const GUARD_MS = 350;

/** @param open ป๊อปอัพเปิดอยู่ไหม — ใช้จับ "เวลาที่เพิ่งเปิด" ให้ถูกจังหวะ
 *    (เรียก hook ไว้ระดับคอมโพเนนต์ที่อยู่ยาวได้ ไม่ต้องผูกกับตัวป๊อปอัพที่เกิด/ตายตามเงื่อนไข) */
export function useOverlayClose(onClose: () => void, open = true) {
  const openedAt = useRef(0);
  const downOnOverlay = useRef(false);
  useEffect(() => { if (open) openedAt.current = Date.now(); }, [open]);

  const onMouseDown = useCallback((e: React.MouseEvent) => {
    downOnOverlay.current = e.target === e.currentTarget;
  }, []);

  const onClick = useCallback((e: React.MouseEvent) => {
    if (e.target !== e.currentTarget) return;      // คลิกโดนกล่องข้างใน ไม่ใช่ฉากหลัง
    if (!downOnOverlay.current) return;            // เริ่มกดจากในกล่อง (ลากข้อความออกมา)
    if (Date.now() - openedAt.current < GUARD_MS) return; // คลิกที่สองของดับเบิลคลิก
    onClose();
  }, [onClose]);

  return { onMouseDown, onClick };
}
