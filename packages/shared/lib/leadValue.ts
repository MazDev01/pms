// ── กติกา "มูลค่าลูกค้าเป้าหมาย" — แหล่งเดียวของทั้งระบบ ────────────────────────
//
// ช่องนี้รับข้อความอิสระ (พิมพ์ "1.4M" · "฿1,400,000" · "1400000" ได้หมด) ตัวแปลงค่าจึงคืน 0
// เมื่ออ่านไม่ออก ถ้าไม่ฟ้องตอนบันทึก เงินที่พิมพ์จะหายเงียบ ๆ แล้วไปโผล่ในรายงานเป็นศูนย์
//
// ⚠️ ต้องประกาศที่เดียว (บทเรียน 10 ส.ค. 69 · ซ้ำอีกครั้ง 25 ส.ค. 69)
//   รอบแรก: เพดานอยู่ในฟอร์มเพิ่มลูกค้าเป้าหมายอย่างเดียว แผงแก้ไขจึงไม่มีเพดาน
//   รอบสอง: ฟอร์ม "เพิ่มงานขายใหม่" (หน้าลูกค้า) ไม่มีทั้งเพดานและการตรวจว่าอ่านออกไหม
//           กรอก "abcxyz" แล้วบันทึกผ่านเป็นงานที่มูลค่า ฿0 เงียบ ๆ
//   → ย้ายมาไว้ที่เดียวตรงนี้ ใครเพิ่มฟอร์มใหม่ต้องเรียกตัวนี้ ห้ามเขียนกฎเอง
import { parseBaht } from "./format";

/** เพดานมูลค่า — สูงกว่างานจริงที่ใหญ่ที่สุดหลายเท่า แต่กันเลขหลุดโลก */
export const MAX_LEAD_VALUE = 100_000_000_000;

/** ข้อความเพดาน — ต้องเป็นประโยคเดียวกันทุกฟอร์ม (เดิมฟอร์มเพิ่มเขียน "100,000 ล้าน" แผงแก้เขียน "100 พันล้าน") */
export const เกินเพดาน = `มูลค่าสูงเกินจริง — กรอกได้ไม่เกิน ${(MAX_LEAD_VALUE / 1e6).toLocaleString("th-TH")} ล้านบาท`;
export const อ่านไม่ออก = "มูลค่าอ่านไม่ออก — กรอกเป็นตัวเลขบวก เช่น 1400000 หรือ 1.4M (เว้นว่างได้ถ้ายังไม่รู้)";

/** ตรวจมูลค่าที่ผู้ใช้พิมพ์ — คืนข้อความที่ต้องแสดง หรือ "" ถ้าใช้ได้
 *  เว้นว่างได้ (ยังไม่รู้มูลค่า) — ไม่ถือว่าผิด */
export function ตรวจมูลค่าลูกค้าเป้าหมาย(raw: string): string {
  const v = (raw ?? "").trim();
  if (!v) return "";
  const n = parseBaht(v);
  if (!(n > 0)) return อ่านไม่ออก;
  if (n > MAX_LEAD_VALUE) return เกินเพดาน;
  return "";
}
