"use client";

// ─── "พร้อมยิงคำขอหรือยัง" — ด่านเดียวที่ทุก hook ที่อ่านข้อมูลต้องผ่าน ─────────────
//
// ⚠️ อย่าใช้ hydrated เดี่ยว ๆ เป็นเงื่อนไข (กับดักที่พลาดมาแล้วหลายรอบ)
//    hydrated แปลว่า "ฟื้น session เสร็จแล้ว" ซึ่งเป็นจริง **แม้ผลลัพธ์คือ "ไม่มี session"**
//    และค่าเริ่มต้นของ session คือสาขาเดโม (CNX) → หน้าที่ยังไม่ล็อกอินจะยิงคำขอ
//    ในนามสาขา CNX ออกไปจริง ๆ
//
// อาการที่เคยเจอจริง (18 ส.ค. 69):
//   • โหมด supabase — ฐานข้อมูลปฏิเสธเงียบ ๆ แล้วค่าตกไปใช้ค่าตั้งต้นแทนค่าที่ HQ ตั้งไว้
//     เรื่องนี้อันตรายกว่า error เสียอีก เพราะ VAT/อายุใบเสนอราคาผิดโดยไม่มีอะไรฟ้อง
//   • โหมด api — ตอบ 401 ยกชุด เห็นเป็น error เต็มหน้าจอตอนอยู่หน้าเข้าสู่ระบบ
//
// โหมด local (เดโม) ไม่มีการล็อกอินจริง จึงต้องโหลดได้ตามปกติ — ห้ามบังคับ isLoggedIn ที่นั่น
import { useRole } from "@pms/shared/context/RoleContext";
import { REAL_BACKEND } from "@pms/shared/lib/data/config";

/** true = รู้ตัวตนแล้วและมีสิทธิ์อ่าน — hook ที่โหลดข้อมูลควรรอค่านี้ก่อนเสมอ */
export function useAuthReady(): boolean {
  const { hydrated, isLoggedIn } = useRole();
  return hydrated && (!REAL_BACKEND || isLoggedIn);
}
