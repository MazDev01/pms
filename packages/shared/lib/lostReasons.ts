// ── เหตุผลที่เสียโอกาส: แสดง "ทุกเหตุผล" ในกราฟ (บอสสั่ง 21 ส.ค. 69) ──────────────
//
// ⚠️ เคยทำผิดมาแล้วรอบหนึ่งในวันเดียวกัน: ยุบทุกเหตุผลที่ไม่อยู่ในรายการมาตรฐานเป็น "อื่นๆ"
//    ผลคือข้อมูลจริงส่วนใหญ่ (ที่บันทึกไว้ก่อนสำนักงานใหญ่แก้รายการ) ถูกกองรวมเป็นก้อนเดียว
//    กราฟเหลือชิ้นเดียวชื่อ "อื่นๆ" — เสียประโยชน์ของกราฟไปทั้งใบ
//
// กติกาที่ใช้ตอนนี้: โชว์ทุกเหตุผลตามจริง เรียงจากมากไปน้อย
//   ยุบเฉพาะ "หางยาว" ที่เกินจำนวนชิ้นที่อ่านไหว (ค่าเริ่มต้น 6) เป็น "อื่นๆ" ก้อนเดียว
//   และก้อนนั้นพกข้อความจริงไว้ใน details ให้ชี้เมาส์ดูได้ — ยุบเพื่ออ่านง่าย ไม่ใช่เพื่อซ่อน
export const OTHER_REASON_LABEL = "อื่นๆ";

export function groupLostReasons<T extends { reason: string; count: number; value?: number }>(
  rows: T[], สูงสุดกี่ชิ้น = 6,
): { reason: string; count: number; value: number; details?: string[] }[] {
  const เรียง = rows
    .map(r => ({ reason: String(r.reason ?? "").trim(), count: r.count, value: r.value ?? 0 }))
    .filter(r => r.reason)
    .sort((a, b) => b.count - a.count);
  if (เรียง.length <= สูงสุดกี่ชิ้น) return เรียง;

  const หัว = เรียง.slice(0, สูงสุดกี่ชิ้น - 1);
  const หาง = เรียง.slice(สูงสุดกี่ชิ้น - 1);
  return [...หัว, {
    reason: OTHER_REASON_LABEL,
    count: หาง.reduce((s, r) => s + r.count, 0),
    value: หาง.reduce((s, r) => s + r.value, 0),
    details: หาง.map(r => `${r.reason} (${r.count})`),
  }];
}

/** เติมก้อน "อื่นๆ" ของดีลที่ปิดไม่สำเร็จแต่ไม่ได้ระบุเหตุผล (บอสสั่ง 21 ส.ค. 69)
 *
 *  ทำไมต้องมีในกราฟ ไม่ใช่เชิงอรรถใต้การ์ด: ยอดในวงกลมคือ "ปิดไม่สำเร็จทั้งหมด"
 *    ถ้าไม่นับกลุ่มที่ไม่ได้ระบุเหตุผลเข้าไปด้วย ผลรวมของชิ้นจะไม่เท่ากับเลขตรงกลาง
 *    คนอ่านจะงงว่าหายไปไหน — และมองไม่เห็นว่า "เราไม่รู้สาเหตุ" อยู่กี่ราย ซึ่งเป็นข้อมูลสำคัญ
 *  ⚠️ ไม่มี = ไม่ต้องใส่ชิ้นเปล่า (ห้ามโชว์ 0 ให้ดูเหมือนมี)
 */
export function withUnspecified(
  rows: { reason: string; count: number; value: number; details?: string[] }[],
  ไม่ได้ระบุ: number,
) {
  if (!(ไม่ได้ระบุ > 0)) return rows;
  return [...rows, { reason: UNSPECIFIED_REASON_LABEL, count: ไม่ได้ระบุ, value: 0,
    details: ["ปิดไม่สำเร็จแต่ไม่ได้บันทึกเหตุผลไว้"] }];
}

export const UNSPECIFIED_REASON_LABEL = "อื่นๆ (ไม่ได้ระบุเหตุผล)";
