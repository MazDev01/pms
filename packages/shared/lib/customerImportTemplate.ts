// ⚠️ ค่าตัวอย่างของ แม่แบบ / จังหวัด / ผู้รับผิดชอบ ต้องส่งมาจากข้อมูลจริงของสาขาที่ล็อกอิน
//    ห้ามฝังค่าตายตัว — เดิมเขียน "โกดังสำเร็จรูป" ไว้ แต่แคตตาล็อกจริงของบริษัทใช้ชื่ออื่น
//    ใครกรอกตามตัวอย่างแล้วนำเข้า จะได้ลูกค้าที่มีแม่แบบซึ่งไม่มีอยู่ในระบบ (ตัวกรองหาไม่เจอ)

import { จับคู่ตามหัวตาราง, แปลงวันที่นำเข้า } from "./importSheet";

export type ImportRow = {
  company: string; name: string; phone: string; email: string; address: string;
  province: string; category: string; joinDate: string; owner: string;
};

export const CSV_HEADERS = [
  "บริษัท", "ผู้ติดต่อ", "โทรศัพท์", "อีเมล", "ที่อยู่", "จังหวัด", "แม่แบบ", "เป็นลูกค้าเมื่อ", "ผู้รับผิดชอบ",
];

/** ชื่อคอลัมน์ที่ยอมรับได้ — ระบบเก่าบางที่ส่งออกเป็นภาษาอังกฤษ จับคู่ให้อัตโนมัติ */
export const ชื่อคอลัมน์: Record<keyof ImportRow, string[]> = {
  company: ["บริษัท", "ชื่อบริษัท", "company"],
  name: ["ผู้ติดต่อ", "ชื่อผู้ติดต่อ", "ชื่อ-สกุล", "contact", "name"],
  phone: ["โทรศัพท์", "เบอร์โทร", "โทร", "phone", "tel"],
  email: ["อีเมล", "email", "e-mail"],
  address: ["ที่อยู่", "ที่อยู่เต็ม", "address"],
  province: ["จังหวัด", "province"],
  category: ["แม่แบบ", "ประเภท", "category", "type"],
  joinDate: ["เป็นลูกค้าเมื่อ", "วันที่เป็นลูกค้า", "วันที่เข้าร่วม", "joindate", "join date", "since"],
  owner: ["ผู้รับผิดชอบ", "ผู้ดูแล", "เจ้าของ", "owner", "sales"],
};

/** ค่าที่ระบบมีจริง ณ ตอนกดโหลดเทมเพลต (ของสาขาที่ล็อกอิน) */
export type ค่าที่ระบบมี = { แม่แบบ: string[]; จังหวัด: string[]; ผู้รับผิดชอบ: string[] };

/** แถวตัวอย่าง 1 แถว — ให้เห็นรูปแบบที่ควรกรอก แล้วพิมพ์ทับได้เลย */
export function แถวตัวอย่าง(ค่า: ค่าที่ระบบมี): string[] {
  return ["บจ. ตัวอย่างสตีล", "คุณสมชาย ใจดี", "081-234-5678", "contact@example.com",
    "26 หมู่ 3 ต.หนองบัว อ.เมือง จ.เชียงใหม่ 50000",
    ค่า.จังหวัด[0] ?? "", ค่า.แม่แบบ[0] ?? "", "05/10/2025", ค่า.ผู้รับผิดชอบ[0] ?? ""];
}

/** แผ่นที่สองของไฟล์เทมเพลต — ลอกค่าจริงจากระบบไว้ให้ก๊อปไปวาง ไม่ต้องเดาว่าพิมพ์อะไรถึงตรง */
export function แผ่นค่าที่เลือกได้(ค่า: ค่าที่ระบบมี) {
  const สูง = Math.max(ค่า.แม่แบบ.length, ค่า.จังหวัด.length, ค่า.ผู้รับผิดชอบ.length, 1);
  return {
    ชื่อ: "ค่าที่เลือกได้",
    หัวตาราง: ["แม่แบบ (ตามแคตตาล็อกของสำนักงานใหญ่)", "จังหวัดที่สาขานี้ดูแล", "ผู้รับผิดชอบของสาขา"],
    แถว: Array.from({ length: สูง }, (_, i) =>
      [ค่า.แม่แบบ[i] ?? "", ค่า.จังหวัด[i] ?? "", ค่า.ผู้รับผิดชอบ[i] ?? ""]),
  };
}

/** เนื้อไฟล์ CSV ของเทมเพลต — ไฟล์เดียวไม่มีแผ่นที่สอง จึงต่อค่าที่เลือกได้เป็นบรรทัดหมายเหตุท้ายไฟล์
 *  บรรทัดหมายเหตุไม่มีชื่อบริษัท ตัวนำเข้าจึงข้ามให้เองอยู่แล้ว (กรองด้วย company) */
export function เนื้อไฟล์Csv(ค่า: ค่าที่ระบบมี): string {
  const หนี = (v: string) => /[",\r\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v;
  const รายการ = (xs: string[]) => xs.join(" | ") || "—";
  return [
    CSV_HEADERS.map(หนี).join(","),
    แถวตัวอย่าง(ค่า).map(หนี).join(","),
    "",
    "# ค่าที่เลือกได้ในระบบ (บรรทัดที่ไม่มีชื่อบริษัท ระบบข้ามให้ตอนนำเข้า)",
    `# แม่แบบ: ${รายการ(ค่า.แม่แบบ)}`,
    `# จังหวัดที่สาขานี้ดูแล: ${รายการ(ค่า.จังหวัด)}`,
    `# ผู้รับผิดชอบของสาขา: ${รายการ(ค่า.ผู้รับผิดชอบ)}`,
    "# วันที่กรอกได้ทั้ง 05/10/2025 · 5/10/2568 · 2025-10-05",
  ].join("\r\n");
}

/** จับคู่คอลัมน์จากตารางที่อ่านได้ → รายการลูกค้าที่พร้อมบันทึก
 *
 *  ทำไมต้องตัดบรรทัดที่ขึ้นต้นด้วย "#" (เจอตอนเขียนเทสต์ 9 ก.ย. 69):
 *    ไฟล์ CSV ที่เราแจกเอง มีบรรทัดหมายเหตุ "# แม่แบบ: …" ต่อท้าย 4-5 บรรทัด
 *    เดิมกรองแค่ "มีชื่อบริษัทไหม" — หมายเหตุพวกนี้มีข้อความในช่องแรก จึงผ่านตัวกรองไปหมด
 *    ผลคือคนที่โหลดฟอร์มไปกรอกแล้วอัปกลับ จะได้ลูกค้าขยะชื่อ "# แม่แบบ: …" ติดมาด้วยทุกครั้ง
 */
export function จับคู่คอลัมน์(rows: string[][]): ImportRow[] {
  return จับคู่ตามหัวตาราง(rows, ชื่อคอลัมน์)
    .map(r => ({ ...r, province: r.province || "กรุงเทพฯ", joinDate: แปลงวันที่นำเข้า(r.joinDate) }))
    .filter(r => r.company && !r.company.trimStart().startsWith("#"));
}
