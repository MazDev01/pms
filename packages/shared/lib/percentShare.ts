// ── แบ่งสัดส่วนเป็นเปอร์เซ็นต์ให้ "รวมได้ 100 พอดี" ─────────────────────────────
//
// ⚠️ ปัดทีละก้อนแล้วเอามาบวกกัน = รวมไม่ได้ 100 (ผลตรวจภายนอก DL-08 · 24 ส.ค. 69)
//    ของจริงที่เจอ: 7 ก้อนขึ้น 25% + 13%×6 = 103% ทั้งที่จำนวนนับรวมกันได้ 16 พอดี
//    ผู้ใช้เห็นแล้วไม่เชื่อตัวเลขทั้งการ์ด
//
// วิธี largest remainder: ปัดลงทุกก้อนก่อน แล้วแจกเศษที่เหลือให้ก้อนที่ "เศษมากที่สุด" ทีละ 1
//   จำนวนเต็มรวมกันได้ 100 เสมอ และลำดับความสำคัญไม่เพี้ยน (ก้อนใหญ่ยังใหญ่กว่าเสมอ)
export function percentShare(values: number[]): number[] {
  const รวม = values.reduce((s, v) => s + (v > 0 ? v : 0), 0);
  if (rวมไม่ได้(รวม)) return values.map(() => 0);
  const ดิบ = values.map(v => ((v > 0 ? v : 0) / รวม) * 100);
  const ปัดลง = ดิบ.map(Math.floor);
  let เหลือ = 100 - ปัดลง.reduce((s, v) => s + v, 0);
  // เรียงตามเศษมาก→น้อย แล้วแจกทีละ 1 · เศษเท่ากันให้ก้อนที่มาก่อน (ผลลัพธ์คงที่ ไม่สุ่ม)
  const ลำดับ = ดิบ.map((v, i) => ({ i, เศษ: v - Math.floor(v) }))
    .sort((a, b) => b.เศษ - a.เศษ || a.i - b.i);
  const ผล = [...ปัดลง];
  for (const { i } of ลำดับ) { if (เหลือ <= 0) break; ผล[i] += 1; เหลือ -= 1; }
  return ผล;
}

function rวมไม่ได้(n: number) { return !isFinite(n) || n <= 0; }
