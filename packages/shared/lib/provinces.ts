// ─── จังหวัด ↔ ภาค (ข้อเท็จจริงทางภูมิศาสตร์ — ไม่ใช่ข้อมูลธุรกิจที่กุขึ้น) ──────────────
//
// แยกออกมาเป็นไฟล์ของตัวเองเพราะมีหลายหน้าที่ต้องใช้คนละบริบทกัน:
//   /hq/customers  → หาภาคของลูกค้าจากจังหวัด (regionOf)
//   /hq/dealers    → เลือกภาคแล้วให้เลือกจังหวัดเฉพาะในภาคนั้น (provincesOfRegion)
// เดิมอยู่ใน customerDb.ts ซึ่งลาก useMemo/ข้อมูลลูกค้า/ใบเสนอราคาติดมาด้วยทั้งชุด
// หน้าที่ต้องการแค่ "รายชื่อจังหวัด" จึงไม่ควรต้องพ่วงของพวกนั้นเข้าไป
//
// สะกดให้ตรงกับ dealer.region (mock.ts seed / hq/dealers / hq/pipeline) = "อีสาน" ไม่ใช่ "ตะวันออกเฉียงเหนือ"
//   เดิมสะกดคนละแบบ → ของสองระบบเทียบกันไม่ตรง (regionDisplay ต้อง special-case "อีสาน" อยู่แล้วเพื่อขยายชื่อเต็ม) · 1.4
export const REGIONS = ["เหนือ", "อีสาน", "กลาง", "ตะวันออก", "ตะวันตก", "ใต้"] as const;
export type Region = (typeof REGIONS)[number];

const REGION_OF: Record<string, Region> = {};
const PROVINCES_OF: Record<string, string[]> = {};
// alias = ชื่อเรียกอีกแบบของจังหวัดเดียวกัน (เช่น "กรุงเทพฯ") — เทียบภาคได้เหมือนกัน
//   แต่ไม่เอาเข้ารายการให้เลือก ไม่งั้นจังหวัดเดียวจะโผล่สองบรรทัดในกล่องเลือกจังหวัด
const put = (region: Region, provinces: string[], alias: string[] = []) => {
  PROVINCES_OF[region] = provinces;
  [...provinces, ...alias].forEach(p => { REGION_OF[p] = region; });
};

put("เหนือ", ["เชียงใหม่", "เชียงราย", "ลำปาง", "ลำพูน", "แม่ฮ่องสอน", "น่าน", "พะเยา", "แพร่", "อุตรดิตถ์"]);
put("อีสาน", ["กาฬสินธุ์", "ขอนแก่น", "ชัยภูมิ", "นครพนม", "นครราชสีมา", "บึงกาฬ", "บุรีรัมย์", "มหาสารคาม", "มุกดาหาร", "ยโสธร", "ร้อยเอ็ด", "เลย", "ศรีสะเกษ", "สกลนคร", "สุรินทร์", "หนองคาย", "หนองบัวลำภู", "อำนาจเจริญ", "อุดรธานี", "อุบลราชธานี"]);
put("กลาง", ["กรุงเทพมหานคร", "กำแพงเพชร", "ชัยนาท", "นครนายก", "นครปฐม", "นครสวรรค์", "นนทบุรี", "ปทุมธานี", "พระนครศรีอยุธยา", "พิจิตร", "พิษณุโลก", "เพชรบูรณ์", "ลพบุรี", "สมุทรปราการ", "สมุทรสงคราม", "สมุทรสาคร", "สระบุรี", "สิงห์บุรี", "สุโขทัย", "สุพรรณบุรี", "อ่างทอง", "อุทัยธานี"], ["กรุงเทพฯ"]);
put("ตะวันออก", ["จันทบุรี", "ฉะเชิงเทรา", "ชลบุรี", "ตราด", "ปราจีนบุรี", "ระยอง", "สระแก้ว"]);
put("ตะวันตก", ["กาญจนบุรี", "ตาก", "ประจวบคีรีขันธ์", "เพชรบุรี", "ราชบุรี"]);
put("ใต้", ["กระบี่", "ชุมพร", "ตรัง", "นครศรีธรรมราช", "นราธิวาส", "ปัตตานี", "พังงา", "พัทลุง", "ภูเก็ต", "ยะลา", "ระนอง", "สงขลา", "สตูล", "สุราษฎร์ธานี"]);

/** ภาคของจังหวัด · จังหวัดที่ไม่รู้จัก = null (หน้าแสดง "—") */
export const regionOf = (province: string): Region | null => REGION_OF[(province ?? "").trim()] ?? null;

/** จังหวัดทั้งหมดในภาคนั้น (เรียงตามที่ประกาศไว้ข้างบน) — ใช้ทำกล่องเลือกจังหวัดที่ผูกกับภาค */
export const provincesOfRegion = (region: string): string[] => PROVINCES_OF[(region ?? "").trim()] ?? [];
