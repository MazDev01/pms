// ── กติกา "ปิดการขายสำเร็จแล้วต้องเดินงานตามหลังให้ครบ" ────────────────────────────
//
// บั๊กจริง (ผู้ใช้แจ้ง 11 ส.ค. 69):
//   ปิดการขายดีลที่ 2 ของลูกค้ารายเดิม แล้ว "ใบเสนอราคายังค้างสถานะเดิม" ไม่กลายเป็นปิดการขายได้
//   ยอดรวมของลูกค้าก็ไม่ขยับ ทั้งที่สถานะลูกค้าเป้าหมายเปลี่ยนเป็นปิดการขายสำเร็จเรียบร้อย
//
// เหตุ: ตัวเรียกเช็ค `status === "PAID" && lead.customerId == null`
//   เงื่อนไขท้ายแปลว่า "ทำเฉพาะลูกค้าเป้าหมายที่ยังไม่เคยเป็นลูกค้า" — ซึ่งพอเป็นดีลที่ 2 ของลูกค้าเดิม
//   (customerId มีค่าแล้ว) ทั้งก้อนจะถูกข้ามไปเงียบ ๆ ไม่มีข้อความ ไม่มี error
//   ทั้งที่งานตามหลังไม่ได้มีแค่ "สร้างลูกค้า" แต่รวม "ปิดใบเสนอราคาของดีลนี้" และ "รวมยอดลูกค้าใหม่" ด้วย
//   (ตัวทำงานจริงรองรับลูกค้าเดิมอยู่แล้วผ่าน knownCustomerId — ติดแค่ด่านนี้ด่านเดียว)
//
// แยกเป็นฟังก์ชันเล็ก ๆ เพื่อให้ "กติกาข้อนี้" มีที่อยู่ที่เดียวและทดสอบได้จริง
// ห้ามเติมเงื่อนไข customerId กลับเข้าไปอีก — นั่นคือตัวบั๊ก

/** ปิดการขายสำเร็จหรือยัง — จริงเมื่อไหร่ ต้องเดินงานตามหลังให้ครบทุกครั้ง */
export function shouldCloseWon(status: LeadRow["status"]): boolean {
  return status === "PAID";
}
