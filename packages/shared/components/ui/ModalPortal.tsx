"use client";

// ─── ป๊อปอัพต้องแขวนที่ระดับหน้าเว็บ ไม่ใช่ฝังอยู่ในกล่องเนื้อหา ────────────────────
//
// ทำไมถึงสำคัญ (ผู้ใช้แจ้ง 11 ส.ค. 69 · เห็นป๊อปอัพซ้อนกันสองอันตอนเด้งขึ้นมา):
//   ฉากหลังของป๊อปอัพใช้ position: fixed ซึ่ง "ปกติ" จะยึดตำแหน่งกับขอบจอ
//   แต่กฎของเบราว์เซอร์คือ ถ้ามีกล่องแม่ชั้นใดชั้นหนึ่งมี transform / filter / perspective อยู่
//   ป๊อปอัพจะเปลี่ยนไปยึดกับกล่องแม่นั้นแทนขอบจอทันที
//   ระบบนี้มีอนิเมชันตอนการ์ดโผล่ (transform เลื่อนขึ้น) → ถ้าเปิดป๊อปอัพจังหวะที่การ์ดยังวิ่งอยู่
//   ป๊อปอัพจะไปยึดกับการ์ด แล้วกระโดดกลับมากลางจอเมื่ออนิเมชันจบ = เห็นเป็นภาพซ้อน/เด้ง
//   (หลักฐานจากภาพหน้าจอผู้ใช้: ป๊อปอัพเดียวกันอยู่คนละตำแหน่ง ห่างกันเท่ากับครึ่งความกว้างเมนูซ้ายพอดี)
//
// แขวนไว้ที่ <body> ตรง ๆ = ไม่มีกล่องแม่ใดมาเปลี่ยนจุดยึดได้อีกเลย ไม่ว่าหน้าไหนจะมีอนิเมชันอะไร
import { useEffect, useState, type ReactNode } from "react";
import { createPortal } from "react-dom";

export function ModalPortal({ children }: { children: ReactNode }) {
  // ตอนเรนเดอร์ฝั่งเซิร์ฟเวอร์ยังไม่มี document — รอให้ถึงเบราว์เซอร์ก่อนค่อยแขวน
  const [ready, setReady] = useState(false);
  useEffect(() => { setReady(true); }, []);
  if (!ready) return null;
  return createPortal(children, document.body);
}
